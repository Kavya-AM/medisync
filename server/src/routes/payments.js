const r = require("express").Router(), PDF = require("pdfkit");
const { Appointment } = require("../models"), { notify } = require("../lib/notify"), { protect } = require("../auth"), { verifySignature } = require("../lib/pay");
const KEY = () => process.env.RAZORPAY_KEY_ID, SECRET = () => process.env.RAZORPAY_KEY_SECRET;
r.use(protect("patient"));
const mine = (req, extra = {}) => Appointment.findOne({ _id: req.params.id, patient: req.user.id, ...extra }).populate("doctor");

r.post("/:id/order", async (req, res) => {
  const a = await mine(req, { status: "booked" });
  if (!a) return res.status(404).json({ error: "Not found" });
  if (a.paid) return res.status(400).json({ error: "Already paid" });
  const amount = (a.doctor.fee || 500) * 100;
  if (!KEY() || !SECRET()) return res.json({ demo: true, amount });          // no keys: demo payment
  const resp = await fetch("https://api.razorpay.com/v1/orders", {
    method: "POST",
    headers: { "Content-Type": "application/json", Authorization: "Basic " + Buffer.from(KEY() + ":" + SECRET()).toString("base64") },
    body: JSON.stringify({ amount, currency: "INR", receipt: String(a._id) }),
  });
  const o = await resp.json();
  if (!resp.ok) return res.status(502).json({ error: "Payment service error" });
  a.orderId = o.id; await a.save();
  res.json({ demo: false, orderId: o.id, amount, keyId: KEY() });
});

r.post("/:id/verify", async (req, res) => {
  const a = await mine(req, { status: "booked" });
  if (!a) return res.status(404).json({ error: "Not found" });
  if (KEY() && SECRET()) {                                                    // real mode: signature is mandatory
    const { paymentId, signature } = req.body;
    if (!verifySignature(a.orderId, paymentId, signature, SECRET())) return res.status(400).json({ error: "Payment could not be verified" });
    a.paymentId = paymentId;
  }
  a.paid = true; a.invoiceNo = a.invoiceNo || "INV-" + Date.now().toString().slice(-8);
  await a.save();
  notify(a.patient, "Payment received", `Receipt ${a.invoiceNo} for your visit on ${a.date} is ready to download.`, "payment");
  res.json(a);
});

r.get("/:id/invoice", async (req, res) => {
  const a = await mine(req, { paid: true });
  if (!a) return res.status(404).json({ error: "No paid invoice for this visit" });
  res.setHeader("Content-Type", "application/pdf");
  res.setHeader("Content-Disposition", `attachment; filename=${a.invoiceNo}.pdf`);
  const d = new PDF({ margin: 50 }); d.pipe(res);
  d.fontSize(24).text("MediSync").fontSize(11).fillColor("#555").text("Payment receipt").moveDown(1.5).fillColor("#000");
  d.fontSize(12).text("Invoice: " + a.invoiceNo).text("Doctor: " + a.doctor.name + " (" + a.doctor.specialty + ")")
    .text("Visit: " + a.date + " at " + a.time).text("Payment ID: " + (a.paymentId || "demo payment")).moveDown()
    .fontSize(16).text("Amount paid: Rs. " + (a.doctor.fee || 500));
  d.moveDown(2).fontSize(9).fillColor("#777").text("Generated by MediSync. Test mode receipts are not valid for tax or insurance claims.");
  d.end();
});
module.exports = r;
